#!/bin/bash
set -euo pipefail

# Target total trajectories per input PDB
TARGET_NSTRUCT=10

# Remember where we started
CURRENT_DIR="$(pwd)"

# Configuration
RFRELAX_BIN="/mnt/c/ubuntu/rosetta.binary.ubuntu.release-408/main/source/bin/relax.static.linuxgccrelease"
UNIPROTSIGNALOUT="uniprot_signal_peptides.csv"

# Step into parent directory
cd ..

# Helper function to count completed runs in a Rosetta scorefile
get_completed_runs() {
    local score_file="$1"
    if [ ! -f "$score_file" ]; then
        echo 0
        return
    fi
    # Count lines starting with 'SCORE:' but exclude header lines containing 'total_score'
    grep '^SCORE:' "$score_file" | grep -v 'total_score' | wc -l
}

while IFS=',' read -r gene np_id nm_id aa_length uniprot signal_start signal_end signal_length status || [ -n "$gene" ]; do
    [ "$gene" = "gene" ] || [ -z "$gene" ] && continue

    echo "=== Processing Gene: $gene ==="
    
    GENE_DIR="results/$gene"
    FOLDED_DIR="$GENE_DIR/folded"
    
    FASTA_FILES=(
        "$GENE_DIR/${gene}_protein_haplotypes.fa"
        "$GENE_DIR/${gene}_protein_path_haplotypes.fa"
    )

    VALID_INPUTS=true
    for fa_file in "${FASTA_FILES[@]}"; do
        if [ ! -f "$fa_file" ]; then
            echo "ERROR: FASTA file missing: $fa_file"
            VALID_INPUTS=false
        fi
    done
    
    if [ "$VALID_INPUTS" = false ]; then
        echo "Skipping $gene due to missing FASTA files."
        continue
    fi

    # 1. Parse FASTA headers
    EXPECTED_REPAIR_PDBS=()
    for fa_file in "${FASTA_FILES[@]}"; do
        while read -r line; do
            header="${line#>}"
            header="${header#"${header%%[![:space:]]*}"}"
            header="${header%"${header##*[![:space:]]}"}"
            id_only="${header%%|*}"
            EXPECTED_REPAIR_PDBS+=("${id_only}_Repair.pdb")
        done < <(grep '^>' "$fa_file")
    done

    # 2. Collect actual Repaired PDB files
    ACTUAL_REPAIR_PDBS=()
    if [ -d "$FOLDED_DIR" ]; then
        while IFS= read -r -d '' pdb_file; do
            ACTUAL_REPAIR_PDBS+=("$(basename "$pdb_file")")
        done < <(find "$FOLDED_DIR" -maxdepth 1 -type f -name "*_Repair.pdb" -print0)
    fi

    # 3. Validate
    IFS=$'\n' SORTED_EXPECTED=($(sort <<<"${EXPECTED_REPAIR_PDBS[*]}"))
    IFS=$'\n' SORTED_ACTUAL=($(sort <<<"${ACTUAL_REPAIR_PDBS[*]}"))
    unset IFS

    VALIDATION_PASSED=true
    if [ "${#SORTED_EXPECTED[@]}" -ne "${#SORTED_ACTUAL[@]}" ]; then
        echo "VALIDATION FAILED for $gene:"
        echo "  Expected ${#SORTED_EXPECTED[@]} PDBs, but found ${#SORTED_ACTUAL[@]} in $FOLDED_DIR"
        VALIDATION_PASSED=false
    else
        for i in "${!SORTED_EXPECTED[@]}"; do
            if [ "${SORTED_EXPECTED[$i]}" != "${SORTED_ACTUAL[$i]}" ]; then
                VALIDATION_PASSED=false
                break
            fi
        done
    fi

    if [ "$VALIDATION_PASSED" = false ]; then
        echo "Mismatch detail for $gene:"
        echo "  Expected PDBs from FASTAs: ${SORTED_EXPECTED[*]}"
        echo "  Repair PDBs found in $FOLDED_DIR: ${SORTED_ACTUAL[*]}"
        echo "Quitting..."
        echo "--------------------------------------------------"
        exit 1
    fi

    echo "Validation PASSED: FASTA headers match existing repaired PDB files (${#SORTED_EXPECTED[@]} files)."

    # 4. Execute Rosetta FastRelax
    pushd "$FOLDED_DIR" > /dev/null || continue
    
    for repair_pdb in "${SORTED_EXPECTED[@]}"; do
        base_name="${repair_pdb%.pdb}" # e.g. APOA2_protein_variant_2_Repair
        score_file="${base_name}.sc"   # e.g. APOA2_protein_variant_2_Repair.sc
        
        # Calculate completed and remaining structures
        completed_runs=$(get_completed_runs "$score_file")
        needed_runs=$((TARGET_NSTRUCT - completed_runs))

        if [ "$needed_runs" -le 0 ]; then
            echo "Skipping $repair_pdb ($completed_runs/$TARGET_NSTRUCT runs completed in $score_file)."
            continue
        fi

        echo "Running Rosetta FastRelax on $repair_pdb (Completed: $completed_runs, Running remaining: $needed_runs)..."
        
        "$RFRELAX_BIN" \
            -in:file:s "$repair_pdb" \
            -relax:fast \
            -nstruct "$needed_runs" \
            -out:file:scorefile "$score_file" \
            -out:path:pdb .
			
		# 2. Cleanup output PDBs generated by Rosetta in current directory (e.g., base_0001.pdb, base_0002.pdb)
        rm -f "${base_name}_"[0-9][0-9][0-9][0-9].pdb
    done

    popd > /dev/null
    echo "Finished $gene."
    echo "--------------------------------------------------"

done < "$CURRENT_DIR/$UNIPROTSIGNALOUT"
